"""Build a deterministic, lane-scoped audit worklist for D001–D084.

This script surfaces exact source/task patterns; it deliberately makes no
semantic role-to-domain decisions. Every mapping remains an independent unit
of review even where role descriptions or ESCO URIs repeat.
"""
from __future__ import annotations

import collections
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]
AUDIT_ROOT = ROOT / "data/career-mapping/_audit"
LANE_DIR = AUDIT_ROOT / "role_fit_lanes_2026_10_05/D001_D084"
INVENTORY = AUDIT_ROOT / "domain_subgroup_role_taxonomy_inventory_2026_10_03.json"
ESCO_TAXONOMY = ROOT / "data/career-mapping/taxonomies/esco_occupations.json"
ONET_ROOT = ROOT / "data/career-mapping/_source_extracts/onet_31_0"
ROLE_LIBRARY = ROOT / "data/career-mapping/role_library_v3_cleaned.json"


def norm(value: str | None) -> str:
    return re.sub(r"\s+", " ", (value or "").strip()).casefold()


def main() -> None:
    source = json.loads(INVENTORY.read_text(encoding="utf-8"))
    rows = [
        dict(row)
        for row in source["role_mappings"]
        if re.fullmatch(r"D\d{3}", str(row.get("domain_id", "")))
        and 1 <= int(row["domain_id"][1:]) <= 84
    ]
    rows.sort(key=lambda r: (int(r["domain_id"][1:]), norm(r.get("role_name"))))
    canonical_rows = json.loads(ROLE_LIBRARY.read_text(encoding="utf-8"))
    canonical_by_key = {
        f"{r.get('domain_id')}|{r.get('role_name')}": r
        for r in canonical_rows
        if re.fullmatch(r"D\d{3}", str(r.get("domain_id", "")))
        and 1 <= int(r["domain_id"][1:]) <= 84
    }
    for row in rows:
        canonical = canonical_by_key.get(row.get("role_key"))
        if canonical:
            row["canonical_review_metadata"] = {
                "domain_fit_review_status": canonical.get("domain_fit_review_status"),
                "domain_fit_review_basis": canonical.get("domain_fit_review_basis"),
                "domain_fit_review_source_refs": canonical.get("domain_fit_review_source_refs") or [],
                "specialization_fit_review_status": canonical.get("specialization_fit_review_status"),
                "specialization_fit_candidate": canonical.get("specialization_fit_candidate"),
                "specialization_fit_review_basis": canonical.get("specialization_fit_review_basis"),
                "specialization_fit_review_source_refs": canonical.get("specialization_fit_review_source_refs") or [],
                "student_path_status": canonical.get("student_path_status") or "active",
                "student_path_exclusion_reason": canonical.get("student_path_exclusion_reason"),
            }

    # The checked-in taxonomy is generated by _tax_00_esco.py from the ESCO
    # English CSV concept export; preserve the URI as the primary-source key.
    esco = json.loads(ESCO_TAXONOMY.read_text(encoding="utf-8-sig"))
    esco_by_code: dict[str, list[tuple[str, dict]]] = collections.defaultdict(list)
    for uri, profile in esco.items():
        esco_by_code[str(profile.get("code") or "")].append((uri, profile))
    # O*NET is an independent primary task source for source-linked mappings.
    # It is US-scoped and therefore supplies transferable task evidence, not
    # country-neutral licensing or labour-market requirements.
    import csv
    onet_profiles = {}
    with (ONET_ROOT / "Occupation Data.txt").open(encoding="utf-8-sig", newline="") as f:
        for profile in csv.DictReader(f, delimiter="\t"):
            onet_profiles[profile["O*NET-SOC Code"]] = {
                "title": profile.get("Title", ""),
                "description": profile.get("Description", ""),
                "tasks": [],
            }
    with (ONET_ROOT / "Task Statements.txt").open(encoding="utf-8-sig", newline="") as f:
        for task in csv.DictReader(f, delimiter="\t"):
            profile = onet_profiles.get(task.get("O*NET-SOC Code", ""))
            if profile and task.get("Task"):
                profile["tasks"].append({
                    "task": task["Task"],
                    "task_type": task.get("Task Type", ""),
                    "date": task.get("Date", ""),
                })

    by_description: dict[str, list[dict]] = collections.defaultdict(list)
    by_uri: dict[str, list[dict]] = collections.defaultdict(list)
    by_role_name: dict[str, list[dict]] = collections.defaultdict(list)
    domain_counts = collections.Counter()
    missing_uri = []
    missing_description = []
    source_reconciliation = collections.Counter()
    source_rows = {}
    for row in rows:
        key = norm(row.get("role_description"))
        if key:
            by_description[key].append(row)
        else:
            missing_description.append(row["role_key"])
        by_role_name[norm(row.get("role_name"))].append(row)
        for uri in row.get("esco_occupation_uris") or []:
            by_uri[uri].append(row)
        if not row.get("esco_occupation_uris") and not row.get("evidence_source_urls"):
            missing_uri.append(row["role_key"])
        linked_profiles = [esco.get(uri) for uri in (row.get("esco_occupation_uris") or [])]
        linked_profiles = [profile for profile in linked_profiles if profile]
        if linked_profiles:
            profile = linked_profiles[0]
            source_match = "uri_match"
        else:
            # Code+label is only a discovery fallback, never a repair by itself.
            candidates = esco_by_code.get(str(row.get("esco_code") or ""), [])
            exact = [(uri, p) for uri, p in candidates if norm(p.get("label")) == norm(row.get("role_name"))]
            profile = exact[0][1] if len(exact) == 1 else None
            source_match = "unique_exact_code_and_label_fallback" if profile else "no_unambiguous_local_esco_profile"
        if profile:
            label_match = norm(profile.get("label")) == norm(row.get("role_name"))
            code_match = str(profile.get("code") or "") == str(row.get("esco_code") or "")
            canonical_task = norm(row.get("role_description"))
            source_task = norm(profile.get("definition"))
            if canonical_task == source_task:
                task_match = "exact"
            elif source_task.startswith(canonical_task) or canonical_task.startswith(source_task):
                task_match = "prefix_or_truncation"
            else:
                task_match = "text_differs"
            source_reconciliation["profile_available"] += 1
            source_reconciliation["label_exact_match" if label_match else "label_differs"] += 1
            source_reconciliation["code_exact_match" if code_match else "code_differs"] += 1
            source_reconciliation[f"task_{task_match}"] += 1
            source_rows[row["role_key"]] = {
                "match_method": source_match,
                "esco_uri": next((uri for uri in (row.get("esco_occupation_uris") or []) if uri in esco), None)
                    or next((uri for uri, p in esco_by_code.get(str(row.get("esco_code") or ""), []) if p is profile), None),
                "esco_label": profile.get("label"),
                "esco_code": profile.get("code"),
                "esco_isco_group": profile.get("isco_group"),
                "esco_definition": profile.get("definition"),
                "esco_alt_labels": profile.get("alt_labels") or [],
                "esco_essential_skills": profile.get("essential_skills") or [],
                "esco_optional_skills": profile.get("optional_skills") or [],
                "canonical_label_matches": label_match,
                "canonical_code_matches": code_match,
                "canonical_task_text_match": task_match,
            }
        else:
            source_reconciliation[source_match] += 1
        onet_codes = row.get("onet_occupation_codes") or []
        onet_evidence = []
        for code in onet_codes:
            op = onet_profiles.get(code)
            if op:
                onet_evidence.append({
                    "onet_soc_code": code,
                    "onet_title": op["title"],
                    "onet_title_matches_canonical_exactly": norm(op["title"]) == norm(row.get("role_name")),
                    "onet_description": op["description"],
                    "onet_tasks": op["tasks"],
                    "onet_profile_url": f"https://www.onetonline.org/link/summary/{code}",
                })
        if onet_evidence:
            source_reconciliation["onet_profile_available"] += 1
        elif onet_codes:
            source_reconciliation["onet_code_not_found_in_local_31_0"] += 1
        elif not profile:
            source_reconciliation["no_esco_or_onet_task_profile"] += 1
        if onet_evidence:
            source_rows.setdefault(row["role_key"], {})["onet_task_profiles"] = onet_evidence
        domain_counts[(row["domain_id"], row["domain_name"])] += 1

    def groups(index: dict[str, list[dict]], *, cross_domain_only=False):
        result = []
        for key, group in index.items():
            domains = sorted({r["domain_id"] for r in group}, key=lambda x: int(x[1:]))
            if len(group) < 2 or (cross_domain_only and len(domains) < 2):
                continue
            result.append({
                "key": key,
                "mapping_count": len(group),
                "domain_ids": domains,
                "records": [r["role_key"] for r in group],
            })
        return sorted(result, key=lambda g: (-g["mapping_count"], g["key"]))

    exact_description_groups = groups(by_description)
    same_uri_cross_domain_groups = groups(by_uri, cross_domain_only=True)
    same_title_cross_domain_groups = groups(by_role_name, cross_domain_only=True)
    current_fit_counts = collections.Counter(
        (r.get("canonical_review_metadata") or {}).get("domain_fit_review_status") or "not_reviewed"
        for r in rows
    )
    current_dispositions = collections.Counter()
    for row in rows:
        review = row.get("canonical_review_metadata") or {}
        fit = review.get("domain_fit_review_status")
        current_dispositions[
            "excluded_from_student_domain_path" if review.get("student_path_status") == "excluded"
            else f"{fit}_domain_fit" if fit else "unreviewed_role_tasks_vs_domain_scope"
        ] += 1

    out = {
        "schema_version": 1,
        "generated_from": str(INVENTORY.relative_to(ROOT)).replace("\\", "/"),
        "scope": {"domain_id_min": "D001", "domain_id_max": "D084", "mapping_count": len(rows)},
        "method": {
            "semantic_decisions_made": True,
            "semantic_decisions_are_lane_scoped": True,
            "exact_description_reuse_is_not_fit_evidence": True,
            "esco_or_isco_grouping_is_not_fit_evidence": True,
            "every_role_key_requires_independent_parent_domain_review": True,
        },
        "counts": {
            "mapping_rows": len(rows),
            "represented_domain_ids": len(domain_counts),
            "fit_statuses": dict(current_fit_counts),
            "canonical_review_statuses": dict(collections.Counter(
                (r.get("canonical_review_metadata") or {}).get("domain_fit_review_status") or "not_reviewed"
                for r in rows
            )),
            "canonical_specialization_review_statuses": dict(collections.Counter(
                (r.get("canonical_review_metadata") or {}).get("specialization_fit_review_status") or "not_reviewed"
                for r in rows
            )),
            "excluded_student_paths": sum(
                (r.get("canonical_review_metadata") or {}).get("student_path_status") == "excluded"
                for r in rows
            ),
            "semantic_dispositions": dict(current_dispositions),
            "rows_with_role_description": len(rows) - len(missing_description),
            "rows_without_role_description": len(missing_description),
            "rows_without_linked_esco_uri": sum(not (r.get("esco_occupation_uris") or []) for r in rows),
            "rows_without_linked_esco_uri_and_source_url": len(missing_uri),
            "distinct_exact_normalized_descriptions": len(by_description),
            "exact_description_duplicate_groups": len(exact_description_groups),
            "exact_description_duplicate_mapping_rows": sum(g["mapping_count"] for g in exact_description_groups),
            "cross_domain_reused_esco_uri_groups": len(same_uri_cross_domain_groups),
            "cross_domain_exact_role_title_groups": len(same_title_cross_domain_groups),
            "esco_source_reconciliation": dict(source_reconciliation),
        },
        "domain_counts": [
            {"domain_id": did, "domain_name": name, "mapping_count": count}
            for (did, name), count in sorted(domain_counts.items(), key=lambda x: int(x[0][0][1:]))
        ],
        "exact_description_duplicate_groups": exact_description_groups,
        "cross_domain_reused_esco_uri_groups": same_uri_cross_domain_groups,
        "cross_domain_exact_role_title_groups": same_title_cross_domain_groups,
        "rows_without_esco_uri_and_source_url": missing_uri,
        "rows_without_role_description": missing_description,
        "records": [
            {
                "role_key": r.get("role_key"),
                "domain_id": r.get("domain_id"),
                "domain_name": r.get("domain_name"),
                "domain_scope": r.get("domain_scope"),
                "role_name": r.get("role_name"),
                "role_description": r.get("role_description"),
                "identity_source": r.get("identity_source"),
                "role_evidence_state": r.get("role_evidence_state"),
                "esco_code": r.get("esco_code"),
                "esco_occupation_uris": r.get("esco_occupation_uris") or [],
                "evidence_source_urls": r.get("evidence_source_urls") or [],
                "onet_occupation_codes": r.get("onet_occupation_codes") or [],
                "role_evidence_state": r.get("role_evidence_state"),
                "role_to_domain_fit_status_before": r.get("role_to_domain_fit_status"),
                "semantic_disposition_before": r.get("semantic_disposition"),
                "student_path_status_before": r.get("student_path_status"),
                "canonical_review_metadata": r.get("canonical_review_metadata"),
                "exact_description_group": norm(r.get("role_description")),
                "source_evidence": source_rows.get(r["role_key"]),
            }
            for r in rows
        ],
    }
    LANE_DIR.mkdir(parents=True, exist_ok=True)
    json_path = LANE_DIR / "D001_D084_inventory_and_triage.json"
    json_path.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    report = [
        "# D001–D084 Deterministic Inventory and Source-Pattern Triage",
        "",
        "Generated by `build_lane_inventory.py`; semantic fit has not been inferred.",
        "",
        "## Baseline",
        "",
        f"- Mapping rows: **{out['counts']['mapping_rows']}** across **{out['counts']['represented_domain_ids']}** represented domains.",
        f"- Fit statuses: `{out['counts']['fit_statuses']}`.",
        f"- Canonical D001-D084 role review statuses: `{out['counts']['canonical_review_statuses']}`.",
        f"- Canonical specialization review statuses: `{out['counts']['canonical_specialization_review_statuses']}`; excluded student paths: **{out['counts']['excluded_student_paths']}**.",
        f"- Exact normalized task descriptions: **{out['counts']['distinct_exact_normalized_descriptions']}**; exact-description duplicate groups: **{out['counts']['exact_description_duplicate_groups']}**.",
        f"- ESCO URI reused across domains: **{out['counts']['cross_domain_reused_esco_uri_groups']}** groups.",
        f"- Exact role title reused across domains: **{out['counts']['cross_domain_exact_role_title_groups']}** groups.",
        f"- Rows without an ESCO concept URI: **{out['counts']['rows_without_linked_esco_uri']}**; without either ESCO URI or explicit source URL: **{out['counts']['rows_without_linked_esco_uri_and_source_url']}**.",
        f"- Local primary ESCO-profile reconciliation: `{out['counts']['esco_source_reconciliation']}`.",
        "- O*NET 31.0 task statements are joined by the exact O*NET-SOC code where the mapping record supplies one; source URLs, task text and US-scope limitation are retained per row.",
        "",
        "## Domain row counts",
        "",
        "| Domain | Name | Mappings |",
        "|---|---|---:|",
    ]
    report.extend(f"| {d['domain_id']} | {d['domain_name']} | {d['mapping_count']} |" for d in out["domain_counts"])
    report += [
        "",
        "## Exact-source pattern triage",
        "",
        "These groups are retrieval/review aids only. Every role mapping is still independently compared with its own parent-domain scope. A repeated description or URI never transfers a prior fit decision.",
        "",
        "### Cross-domain reused ESCO URIs",
        "",
    ]
    for g in same_uri_cross_domain_groups:
        report.append(f"- `{g['key']}` — {', '.join(g['records'])}")
    report += ["", "### Cross-domain exact task-description reuse", ""]
    for g in exact_description_groups:
        if len(g["domain_ids"]) > 1:
            report.append(f"- {g['mapping_count']} mappings across {', '.join(g['domain_ids'])}: {', '.join(g['records'])}")
    report += ["", "### Missing both ESCO URI and source URL", ""]
    report.extend(f"- `{key}`" for key in missing_uri)
    report += [
        "",
        "## Per-mapping evidence worklist",
        "",
        "The full row-level worklist, including each parent scope, task description and exact ESCO URI, is in `D001_D084_inventory_and_triage.json`.",
        "Where available, that record also contains the matched checked-in ESCO definition, alternative labels, essential/optional skills and exact text/code/label comparison. O*NET 31.0 task statements are joined only by the recorded SOC code. Official concept/profile URLs are retained as locators. ESCO/O*NET task evidence can inform the job-task comparison; it does not decide parent-domain fit, and O*NET reflects a US occupational framework.",
        "",
        "## Decision gate",
        "",
        "No automatic semantic repair is permitted by this triage. A fit status or path exclusion may be changed only after the linked role tasks are checked against this exact parent domain and the decision rationale cites the task evidence and its limitations.",
        "",
    ]
    report += ["## Exact ESCO profile discrepancies (source-check queue)", ""]
    for r in out["records"]:
        e = r.get("source_evidence") or {}
        if not e:
            continue
        if e.get("canonical_task_text_match") == "text_differs" or e.get("canonical_label_matches") is False or e.get("canonical_code_matches") is False:
            esco_profile = e.get("esco_source_profile") or e
            report.append(
                f"- `{r['role_key']}` — source match `{e.get('match_method')}`; "
                f"label `{r['role_name']}` vs `{esco_profile.get('esco_label')}`; "
                f"code `{r.get('esco_code')}` vs `{esco_profile.get('esco_code')}`; "
                f"task comparison `{esco_profile.get('canonical_task_text_match')}`; "
                f"profile [{esco_profile.get('esco_uri')}]({esco_profile.get('esco_uri')})."
            )
    if not any((r.get("source_evidence") or {}).get("canonical_task_text_match") == "text_differs" or (r.get("source_evidence") or {}).get("canonical_label_matches") is False or (r.get("source_evidence") or {}).get("canonical_code_matches") is False for r in out["records"]):
        report.append("- None.")
    report.append("")
    md_path = LANE_DIR / "D001_D084_inventory_and_triage.md"
    md_path.write_text("\n".join(report), encoding="utf-8")
    print(json.dumps({"counts": out["counts"], "json": str(json_path), "markdown": str(md_path)}, indent=2))


if __name__ == "__main__":
    main()
