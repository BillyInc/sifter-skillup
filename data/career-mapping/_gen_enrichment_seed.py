#!/usr/bin/env python3
"""Generate backend/seed_phase8_9_enrichment.sql — one-file SQL seed for Phase 8 & 9.
Maps CSV data to deterministic UUIDs via the same uuid5 namespace as _gen_career_seed.py.
Run AFTER migration_career_v2.sql + migration_admission_intelligence.sql + migration_enrichment_v1.sql.
Output: single self-contained SQL file you paste into Supabase SQL Editor.
"""
import csv, os, uuid, json, hashlib

HERE = os.path.dirname(os.path.abspath(__file__))
NS = uuid.UUID("5c1f7e00-0000-4000-8000-0000ca4ee401")

def uid(*parts):
    return str(uuid.uuid5(NS, "|".join(parts)))

def q(s):
    if s is None or s == "": return "NULL"
    return "'" + str(s).replace("'", "''") + "'"

def jsonb(v):
    if v is None or v == "": return "'{}'::jsonb"
    return "'" + json.dumps(v, ensure_ascii=False).replace("'", "''") + "'::jsonb"

def num(v):
    if v is None or v == "": return "NULL"
    return str(v)

SQL = []
SQL.append("-- AUTO-GENERATED by data/career-mapping/_gen_enrichment_seed.py — DO NOT EDIT")
SQL.append("-- Phase 8 (Admission Intelligence) + Phase 9 (Enrichment) data seed.")
SQL.append("-- Run AFTER migration_career_v2.sql, migration_admission_intelligence.sql, migration_enrichment_v1.sql")
SQL.append("-- Paste into Supabase SQL Editor and run.")
SQL.append("SET search_path TO skillup_dev;")
SQL.append("BEGIN;")
SQL.append("")

# ── Certifications enrichment ──────
csvpath = os.path.join(HERE, "_enrichment", "certs_enrichment.csv")
if os.path.exists(csvpath):
    rows = list(csv.DictReader(open(csvpath, encoding="utf-8")))
    SQL.append(f"-- Certifications enrichment: {len(rows)} rows")
    SQL.append("UPDATE skillup_dev.domain_certifications SET")
    SQL.append("  official_url = sub.official_url,")
    SQL.append("  seniority_tier = sub.seniority_tier,")
    SQL.append("  tier_type = sub.tier_type::text,")
    SQL.append("  price = sub.price,")
    SQL.append("  currency = sub.currency::text,")
    SQL.append("  price_as_of = sub.price_as_of::date,")
    SQL.append("  price_source = sub.price_source")
    SQL.append("FROM (VALUES")
    vals = []
    for r in rows:
        did = uid("domain", r["domain_key"])
        vals.append(f"  ({q(did)}, {q(r['cert_name'])}, {q(r['cert_body'])}, {q(r.get('official_url'))}, {num(r.get('seniority_tier'))}, {q(r.get('tier_type'))}, {num(r.get('price'))}, {q(r.get('currency'))}, {q(r.get('price_as_of'))}, {q(r.get('price_source'))})")
    SQL.append(",\n".join(vals))
    SQL.append(") AS sub(domain_id, cert_name, cert_body, official_url, seniority_tier, tier_type, price, currency, price_as_of, price_source)")
    SQL.append("WHERE skillup_dev.domain_certifications.domain_id = sub.domain_id")
    SQL.append("  AND skillup_dev.domain_certifications.name = sub.cert_name")
    SQL.append("  AND skillup_dev.domain_certifications.body = sub.cert_body;")
    SQL.append("")

# ── Skills URIs ──────
csvpath = os.path.join(HERE, "_enrichment", "skills_uris.csv")
if os.path.exists(csvpath):
    rows = list(csv.DictReader(open(csvpath, encoding="utf-8")))
    SQL.append(f"-- Skills ESCO URIs: {len(rows)} rows")
    # Foundation skills — per domain, merge into foundation_skill_uris JSONB
    foundation = [r for r in rows if r["level"] == "foundation"]
    if foundation:
        by_domain = {}
        for r in foundation:
            by_domain.setdefault(r["key"], {})[r["skill_name"]] = r["uri"]
        for dk, uris in by_domain.items():
            did = uid("domain", dk)
            SQL.append(f"UPDATE skillup_dev.domains SET foundation_skill_uris = foundation_skill_uris || {jsonb(uris)} WHERE id = {q(did)};")
    # Cluster skills — per subgroup
    cluster = [r for r in rows if r["level"] == "cluster"]
    if cluster:
        by_sg = {}
        for r in cluster:
            parts = r["key"].split("|")
            dk2 = parts[0]
            isco = parts[1] if len(parts) > 1 else r.get("isco_submajor", "")
            by_sg.setdefault((dk2, isco), {})[r["skill_name"]] = r["uri"]
        for (dk2, isco), uris in by_sg.items():
            did = uid("domain", dk2)
            sgid = uid("subgroup", dk2, str(isco))
            SQL.append(f"UPDATE skillup_dev.domain_subgroups SET cluster_skill_uris = cluster_skill_uris || {jsonb(uris)} WHERE id = {q(sgid)} AND domain_id = {q(did)};")
    # Role skills — append to JSONB arrays
    role_essential = [r for r in rows if r["level"] == "role_essential"]
    role_optional = [r for r in rows if r["level"] == "role_optional"]
    for label, rrows in [("essential_skill_uris", role_essential), ("optional_skill_uris", role_optional)]:
        by_role = {}
        for r in rrows:
            by_role.setdefault(r["key"], []).append(r["uri"])
        for rk, uris in by_role.items():
            arr_literal = "'{" + ",".join('"' + u.replace("\\", "\\\\").replace('"', '\\"') + '"' for u in uris) + "}'"
            SQL.append(f"UPDATE skillup_dev.domain_roles SET {label} = {label} || {arr_literal}::jsonb WHERE role_key = {q(rk)};")
    SQL.append("")

# ── Tools demand re-rank ──────
csvpath = os.path.join(HERE, "_enrichment", "tools_demand.csv")
if os.path.exists(csvpath):
    rows = list(csv.DictReader(open(csvpath, encoding="utf-8")))
    SQL.append(f"-- Tools demand re-rank: {len(rows)} rows")
    SQL.append("UPDATE skillup_dev.domain_tools SET")
    SQL.append("  demand_score = sub.demand_score,")
    SQL.append("  demand_source = sub.demand_source,")
    SQL.append("  demand_as_of = sub.demand_as_of::date,")
    SQL.append("  tool_url = sub.tool_url")
    SQL.append("FROM (VALUES")
    vals = []
    for r in rows:
        did = uid("domain", r["domain_key"])
        sg = r.get("isco_submajor", "")
        vals.append(f"  ({q(did)}, {q(r['tool_name'])}, {num(r.get('demand_score'))}, {q(r.get('demand_source'))}, {q(r.get('demand_as_of'))}, {q(r.get('tool_url'))})")
    SQL.append(",\n".join(vals))
    SQL.append(") AS sub(domain_id, tool_name, demand_score, demand_source, demand_as_of, tool_url)")
    SQL.append("WHERE skillup_dev.domain_tools.domain_id = sub.domain_id")
    SQL.append("  AND skillup_dev.domain_tools.tool_name = sub.tool_name;")
    SQL.append("")

# ── Roles currency ──────
csvpath = os.path.join(HERE, "_enrichment", "roles_currency.csv")
if os.path.exists(csvpath):
    rows = list(csv.DictReader(open(csvpath, encoding="utf-8")))
    SQL.append(f"-- Roles currency status: {len(rows)} rows")
    SQL.append("UPDATE skillup_dev.domain_roles SET")
    SQL.append("  currency_status = sub.currency_status,")
    SQL.append("  currency_source = sub.currency_source,")
    SQL.append("  currency_verified_at = sub.currency_verified_at::date")
    SQL.append("FROM (VALUES")
    vals = []
    for r in rows:
        rid = uid("role", r["role_key"])
        vals.append(f"  ({q(rid)}, {q(r['currency_status'])}, {q(r.get('currency_source'))}, {q(r.get('currency_verified_at'))})")
    SQL.append(",\n".join(vals))
    SQL.append(") AS sub(id, currency_status, currency_source, currency_verified_at)")
    SQL.append("WHERE skillup_dev.domain_roles.id = sub.id;")
    SQL.append("")

# ── JAMB Floor ──────
csvpath = os.path.join(HERE, "_enrichment", "jamb_floor.csv")
if os.path.exists(csvpath):
    rows = list(csv.DictReader(open(csvpath, encoding="utf-8")))
    SQL.append(f"-- National JAMB floor: {len(rows)} rows")
    for r in rows:
        SQL.append(f"INSERT INTO skillup_dev.national_jamb_floor (year, floor_score, context_note, source_url)")
        SQL.append(f"VALUES ({num(r['year'])}, {num(r['floor_score'])}, {q(r.get('context_note'))}, {q(r.get('source_url'))})")
        SQL.append(f"ON CONFLICT (year) DO UPDATE SET floor_score = EXCLUDED.floor_score, context_note = EXCLUDED.context_note, source_url = EXCLUDED.source_url, updated_at = NOW();")
    SQL.append("")

# ── School Aggregate Formulas ──────
csvpath = os.path.join(HERE, "_enrichment", "admission_formulas_2025.csv")
if os.path.exists(csvpath):
    rows = list(csv.DictReader(open(csvpath, encoding="utf-8")))
    SQL.append(f"-- School aggregate formulas: {len(rows)} rows")
    for r in rows:
        SQL.append(f"INSERT INTO skillup_dev.school_aggregate_formula (id, school_id, year, jamb_weight, postutme_weight, olevel_weight, description, source_url)")
        SQL.append(f"SELECT {q(uid('agg_formula', r['school_name'], str(r['year'])))}, s.id, {num(r['year'])}, {num(r['jamb_weight'])}, {num(r['postutme_weight'])}, {num(r['olevel_weight'])}, {q(r.get('description'))}, {q(r.get('source_url'))}")
        SQL.append(f"FROM skillup_dev.schools s WHERE s.name = {q(r['school_name'])}")
        SQL.append(f"ON CONFLICT (school_id, year) DO UPDATE SET jamb_weight = EXCLUDED.jamb_weight, postutme_weight = EXCLUDED.postutme_weight, olevel_weight = EXCLUDED.olevel_weight, description = EXCLUDED.description, source_url = EXCLUDED.source_url;")
    SQL.append("")

# ── Programme × School Cut-offs ──────
csvpath = os.path.join(HERE, "_enrichment", "admission_cutoffs_2025.csv")
if os.path.exists(csvpath):
    rows = list(csv.DictReader(open(csvpath, encoding="utf-8")))
    SQL.append(f"-- Programme × school cut-offs: {len(rows)} rows")
    for r in rows:
        conflict_id = uid("cutoff", r["school_name"], r["programme_name"], str(r["year"]), r["form"])
        SQL.append(f"INSERT INTO skillup_dev.programme_school_cutoff (id, school_id, programme_id, jamb_programme_id, year, aggregate_cutoff, jamb_cutoff, postutme_cutoff, form, source_url)")
        SQL.append(f"SELECT {q(conflict_id)}, s.id, p.id, (SELECT j.id FROM skillup_dev.jamb_programmes j WHERE j.name = {q(r['programme_name'])} LIMIT 1), {num(r['year'])}, {num(r.get('aggregate_cutoff'))}, {num(r.get('jamb_cutoff'))}, {num(r.get('postutme_cutoff'))}, {q(r['form'])}, {q(r['source_url'])}")
        SQL.append(f"FROM skillup_dev.schools s, skillup_dev.programmes p")
        SQL.append(f"WHERE s.name = {q(r['school_name'])} AND p.name = {q(r['programme_name'])}")
        SQL.append(f"ON CONFLICT (school_id, programme_id, year, form) DO UPDATE SET jamb_programme_id = EXCLUDED.jamb_programme_id, aggregate_cutoff = EXCLUDED.aggregate_cutoff, jamb_cutoff = EXCLUDED.jamb_cutoff, postutme_cutoff = EXCLUDED.postutme_cutoff, source_url = EXCLUDED.source_url;")
    SQL.append("")
    # backfill any legacy rows that predate the jamb_programme_id column:
    # 1) exact name match (canonical programme name == JAMB name)
    SQL.append("UPDATE skillup_dev.programme_school_cutoff c SET jamb_programme_id = j.id")
    SQL.append("FROM skillup_dev.programmes p JOIN skillup_dev.jamb_programmes j ON j.name = p.name")
    SQL.append("WHERE c.programme_id = p.id AND c.jamb_programme_id IS NULL;")
    # 2) via the curated programme_mapping bridge (covers renamed programmes,
    #    e.g. canonical "Law" -> JAMB "Civil Law")
    SQL.append("UPDATE skillup_dev.programme_school_cutoff c SET jamb_programme_id = pm.jamb_programme_id")
    SQL.append("FROM skillup_dev.programme_mapping pm")
    SQL.append("WHERE c.programme_id = pm.programme_id AND c.jamb_programme_id IS NULL;")

# ── Course Competitiveness ──────
csvpath = os.path.join(HERE, "_enrichment", "admission_competitiveness_2025.csv")
if os.path.exists(csvpath):
    rows = list(csv.DictReader(open(csvpath, encoding="utf-8")))
    SQL.append(f"-- National competitiveness: {len(rows)} rows")
    for r in rows:
        SQL.append(f"INSERT INTO skillup_dev.course_competitiveness (id, broad_course, year, applied, admitted, ratio, source, note)")
        SQL.append(f"VALUES ({q(uid('competitiveness', r['broad_course'], str(r['year'])))}, {q(r['broad_course'])}, {num(r['year'])}, {num(r.get('applied'))}, {num(r.get('admitted'))}, {num(r.get('ratio'))}, {q(r.get('source'))}, {q(r.get('note'))})")
        SQL.append(f"ON CONFLICT (broad_course, year) DO UPDATE SET applied = EXCLUDED.applied, admitted = EXCLUDED.admitted, ratio = EXCLUDED.ratio, source = EXCLUDED.source, note = EXCLUDED.note;")
    SQL.append("")

# ── Admission Snapshot ──────
csvpath = os.path.join(HERE, "_enrichment", "admission_snapshot.csv")
if os.path.exists(csvpath):
    rows = list(csv.DictReader(open(csvpath, encoding="utf-8")))
    SQL.append(f"-- Admission snapshot version: {len(rows)} rows")
    for r in rows:
        SQL.append("UPDATE skillup_dev.admission_snapshot_version SET is_active = false WHERE is_active = true;")
        SQL.append(f"INSERT INTO skillup_dev.admission_snapshot_version (id, label, year, compiler, notes, is_active)")
        SQL.append(f"VALUES ({q(uid('snapshot', r['label']))}, {q(r['label'])}, {num(r['year'])}, {q(r.get('compiler'))}, {q(r.get('notes'))}, {'true' if r.get('is_active', 'true').lower() == 'true' else 'false'})")
        SQL.append(f"ON CONFLICT (id) DO UPDATE SET label = EXCLUDED.label, year = EXCLUDED.year, compiler = EXCLUDED.compiler, notes = EXCLUDED.notes, is_active = EXCLUDED.is_active;")
    SQL.append("")

# ── Enrichment version tracking ──────
SQL.append("-- Enrichment version tracking")
try:
    import subprocess
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True,
                            text=True, cwd=HERE).stdout.strip() or "unknown"
except OSError:
    commit = "unknown"
empty_jsonb = "'{}'::jsonb"
SQL.append(f"INSERT INTO skillup_dev.enrichment_version (source_commit_hash, seed_name, rows_upserted, applied_at)")
SQL.append(f"SELECT {q(commit)}, 'admission', (SELECT COUNT(*) FROM skillup_dev.programme_school_cutoff), NOW()")
SQL.append(f"WHERE EXISTS (SELECT 1 FROM skillup_dev.programme_school_cutoff LIMIT 1);")
SQL.append(f"INSERT INTO skillup_dev.enrichment_version (source_commit_hash, seed_name, rows_upserted, applied_at)")
SQL.append(f"SELECT {q(commit)}, 'certs', (SELECT COUNT(*) FROM skillup_dev.domain_certifications WHERE official_url IS NOT NULL), NOW()")
SQL.append(f"WHERE EXISTS (SELECT 1 FROM skillup_dev.domain_certifications WHERE official_url IS NOT NULL LIMIT 1);")
SQL.append(f"INSERT INTO skillup_dev.enrichment_version (source_commit_hash, seed_name, rows_upserted, applied_at)")
SQL.append(f"SELECT {q(commit)}, 'tools', (SELECT COUNT(*) FROM skillup_dev.domain_tools WHERE demand_score IS NOT NULL), NOW()")
SQL.append(f"WHERE EXISTS (SELECT 1 FROM skillup_dev.domain_tools WHERE demand_score IS NOT NULL LIMIT 1);")
_skills_count = "(SELECT COUNT(*) FROM skillup_dev.domains WHERE foundation_skill_uris != " + empty_jsonb + ")"
SQL.append(f"INSERT INTO skillup_dev.enrichment_version (source_commit_hash, seed_name, rows_upserted, applied_at)")
SQL.append("SELECT " + q(commit) + ", 'skills', " + _skills_count + ", NOW()")
SQL.append("WHERE EXISTS (SELECT 1 FROM skillup_dev.domains WHERE foundation_skill_uris != " + empty_jsonb + " LIMIT 1);")
SQL.append(f"INSERT INTO skillup_dev.enrichment_version (source_commit_hash, seed_name, rows_upserted, applied_at)")
SQL.append(f"SELECT {q(commit)}, 'roles_currency', (SELECT COUNT(*) FROM skillup_dev.domain_roles WHERE currency_status IS NOT NULL), NOW()")
SQL.append(f"WHERE EXISTS (SELECT 1 FROM skillup_dev.domain_roles WHERE currency_status IS NOT NULL LIMIT 1);")

SQL.append("")
SQL.append("COMMIT;")

sql_text = "\n".join(SQL)
outpath = os.path.normpath(os.path.join(HERE, "..", "..", "backend", "seed_phase8_9_enrichment.sql"))
with open(outpath, "w", encoding="utf-8") as f:
    f.write(sql_text)
print(f"Generated {outpath}  ({os.path.getsize(outpath):,} bytes, ~{len(sql_text.splitlines())} lines)")