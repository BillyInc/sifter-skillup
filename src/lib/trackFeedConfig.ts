export function searchTracks(query: string): MonitoredTrack[] {
  if (!query.trim()) return ALL_MONITORABLE_TRACKS;
  const q = query.toLowerCase();
  return ALL_MONITORABLE_TRACKS.filter(
    t => t.label.toLowerCase().includes(q) || t.fieldId.includes(q) || t.id.includes(q),
  );
}
