type FeatherProps = { name: string; size?: number; color?: string; style?: unknown; [key: string]: unknown };

export const Feather = Object.assign(
  function Feather({ name, size = 16, color = "currentColor", style }: FeatherProps) {
    const Icon = icons[name] ?? Circle;
    return (
      <View style={[styles.box, { width: size, height: size }, style as never]} pointerEvents="none">
        <Icon size={size} color={color} strokeWidth={2} aria-hidden />
      </View>
    );
  },
  { glyphMap: icons },
);

const styles = StyleSheet.create({
  box: { alignItems: "center", justifyContent: "center", flexShrink: 0 },
});
